#!/usr/bin/env python3
"""Patch the platform-util dvb.ko (gbquad4kpro, vuduo4klite) so a held IR key repeats smoothly.

dev_input_init registers the "gigablue remote control" input device and then replaces the
kernel's per-device autorepeat timer (input_dev.timer.function / .data) with the driver's own
input_repeat_key().  That function only sets a flag one repeat-delay (400 ms) after the press
and never re-arms; from then on input_p_callback emits one EV_KEY value 2 event per *IR frame*
(NEC style remotes send a repeat frame every ~108 ms => ~9 repeats/s, and a single lost frame
is a visible stall).  A Bluetooth/HID remote instead uses the kernel's software autorepeat
(250 ms / 33 ms), which is why fast scrolling is smooth there.

Why the driver does that: input_register_device() only installs the kernel's autorepeat timer
(function + data) when rep[] is still zero, and the driver pre-sets rep[] to 400/125 ms, so it
has to supply a timer function itself - and the kernel's own input_repeat_key is not exported.

This patch leaves rep[] zero before registration (so the kernel installs its real autorepeat
timer) and stores --delay / --period into input_dev.rep[] right after input_register_device(),
in the place where the driver used to override the timer.  Repeat events are then generated by
the kernel timer every --period ms while the IR frames merely keep the key "pressed" (the
driver's 150 ms key-up timer is untouched).  The driver's own repeat path is gated by the flag
that only its input_repeat_key set, so it simply stays dormant.

The script parses the ELF, finds dev_input_init and the stores by instruction pattern + the
relocation of the literal (it must reference input_repeat_key); register choice does not matter.
Rewritten words: the 4 rep[] stores/movs before the register call, and the 4 words that load and
store the timer override after it.
Anything unexpected => exit status 2 and the file is left untouched.  Already patched files are
reported and left alone (exit 0).  The file size does not change.

Usage: patch_dvb_ir.py [--check] [--no-fresh-press] [--delay MS] [--period MS] [--keyup MS] <path/to/dvb.ko>
  defaults: --delay 600 --period 100; --keyup (optional) changes the 150 ms 'no IR frame => key
  released' timeout. NEC repeat frames come every ~108 ms, so one lost frame already exceeds 150 ms,
  releases the key and costs a new --delay before repeating (the 'scroll stops' symptom); 240 survives
  one lost frame but lets the key repeat up to that long after the real release.
Exit status: 0 patched / already patched, 2 unrecognised build (file untouched), 1 usage.

Side effect on the Enigma2 side: long-press is detected by counting repeat events
(config.misc.longkey_threshold, default 4), so at 100 ms a long press fires after
delay + 4*period instead of delay + 4*108 ms.  Raise the threshold if that is too early.

Recipe use (same pattern as patch_dvb_acm.py):
    SRC_URI += "file://patch_dvb_ir.py"
    do_install:append() {
        python3 ${UNPACKDIR}/patch_dvb_ir.py ${D}/home/root/platform/dvb.ko \\
            || bbwarn "dvb.ko IR repeat patch not applied (unrecognised dvb.ko build)"
    }
"""
import struct
import sys

FUNC = "dev_input_init"
TIMER_FN = "input_repeat_key"
OFF_TIMER_FN, OFF_TIMER_DATA = 0xd8, 0xdc          # input_dev.timer.function / .data (4.1, arm32)
OFF_REP_DELAY, OFF_REP_PERIOD = 0xe4, 0xe8         # input_dev.rep[REP_DELAY] / rep[REP_PERIOD]
ORIG_DELAY, ORIG_PERIOD = 400, 125
NOP = 0xe1a00000                                    # mov r0, r0
STR_BASE = 0xe5800000                               # str rt, [rn, #imm12]


class Refuse(Exception):
    pass


def u32(b, o):
    return struct.unpack_from("<I", b, o)[0]


def parse_elf(d):
    """Return (text_file_offset, func_start, func_size, {text_offset: symbol_name} relocs)."""
    if d[:4] != b"\x7fELF" or d[4] != 1 or d[5] != 1:
        raise Refuse("not a 32-bit little endian ELF")
    if struct.unpack_from("<H", d, 18)[0] != 40:
        raise Refuse("not an ARM object")
    shoff = u32(d, 32)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 46)
    raw = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    stro = raw[shstrndx][4]
    secs = {}
    for i, r in enumerate(raw):
        s = stro + r[0]
        secs[d[s:d.index(b"\0", s)].decode()] = (i, r)
    for need in (".text", ".symtab", ".strtab", ".rel.text"):
        if need not in secs:
            raise Refuse("no " + need)
    text_idx, text = secs[".text"]
    sym, strtab = secs[".symtab"][1], secs[".strtab"][1]
    names, found = [], []
    for o in range(sym[4], sym[4] + sym[5], 16):
        st_name, st_value, st_size, st_info, _other, st_shndx = struct.unpack_from("<IIIBBH", d, o)
        s = strtab[4] + st_name
        nm = d[s:d.index(b"\0", s)].decode()
        names.append(nm)
        if st_shndx == text_idx and (st_info & 0xf) == 2 and nm == FUNC:
            found.append((st_value, st_size))
    if len(found) != 1:
        raise Refuse("%s not found (%d symbols)" % (FUNC, len(found)))
    rel = secs[".rel.text"][1]
    relocs = {}
    for o in range(rel[4], rel[4] + rel[5], 8):
        r_offset, r_info = struct.unpack_from("<II", d, o)
        relocs[r_offset] = names[r_info >> 8]
    return text[4], found[0][0], found[0][1], relocs


def is_str(w, off):
    """str Rt, [Rn, #off] (offset addressing, no writeback). Returns (Rt, Rn) or None."""
    if (w & 0xfff00000) == 0xe5800000 and (w & 0xfff) == off:
        return (w >> 12) & 0xf, (w >> 16) & 0xf
    return None


def movw(rd, imm):
    return 0xe3000000 | ((imm >> 12) << 16) | (rd << 12) | (imm & 0xfff)


def mov_imm_value(w, rd):
    """Value if w is 'mov rd, #imm' (ARM modified immediate) or 'movw rd, #imm16', else None."""
    if (w & 0xfffff000) == (0xe3a00000 | (rd << 12)):
        imm8, rot = w & 0xff, (w >> 8) & 0xf
        return ((imm8 >> (2 * rot)) | (imm8 << (32 - 2 * rot))) & 0xffffffff if rot else imm8
    if (w & 0xfff0f000) == (0xe3000000 | (rd << 12)):
        return ((w >> 4) & 0xf000) | (w & 0xfff)
    return None


def plan(d, delay, period):
    """Return (list of (file_offset, old_word, new_word), already_patched)."""
    text_off, fstart, fsize, relocs = parse_elf(d)
    base = text_off + fstart
    words = [u32(d, base + 4 * i) for i in range(fsize // 4)]
    foff = lambda i: base + 4 * i

    def find_rep_pair():
        """Index of 'str rt,[rn,#0xe4]' followed (<=3 words later) by 'str rt2,[rn,#0xe8]'."""
        for i, w in enumerate(words):
            a = is_str(w, OFF_REP_DELAY)
            if not a:
                continue
            for k in range(i + 1, min(i + 4, len(words))):
                b = is_str(words[k], OFF_REP_PERIOD)
                if b and b[1] == a[1]:
                    return i, k
        return None

    def imm_before(i, rt):
        for j in range(i - 1, max(i - 4, -1), -1):
            v = mov_imm_value(words[j], rt)
            if v is not None:
                return j, v
        return None

    has_lit = any(relocs.get(fstart + 4 * k) == TIMER_FN for k in range(fsize // 4))
    fn_idx = [i for i, w in enumerate(words) if is_str(w, OFF_TIMER_FN)]

    if not fn_idx:
        # already patched? the literal is still in the pool; rep[] stores must carry our values
        pair = find_rep_pair() if has_lit else None
        if not pair:
            raise Refuse("timer override stores not recognised")
        vals = []
        for i in pair:
            rt = is_str(words[i], OFF_REP_DELAY if i == pair[0] else OFF_REP_PERIOD)[0]
            r = imm_before(i, rt)
            vals.append(r[1] if r else None)
        if vals == [delay, period]:
            return [], True
        raise Refuse("already patched with different timing %s ms; start from the original" % vals)

    if len(fn_idx) != 1:
        raise Refuse("%d stores to timer.function" % len(fn_idx))
    i_fn = fn_idx[0]
    rt, rn = is_str(words[i_fn], OFF_TIMER_FN)
    # [ldr rt,=input_repeat_key][str ..,#0xdc][str ..,#0x18][str rt,[rn,#0xd8]]
    j = i_fn - 3
    v = words[j]
    if not ((v & 0xff7ff000) == (0xe51f0000 | (rt << 12)) and (v & 0x00800000)
            and relocs.get(fstart + 4 * j + 8 + (v & 0xfff)) == TIMER_FN):
        raise Refuse("timer function literal not where expected")
    i_data, i_dev = j + 1, j + 2
    st_data = is_str(words[i_data], OFF_TIMER_DATA)
    st_dev = is_str(words[i_dev], 0x18)
    if not st_data or st_data[1] != rn or not st_dev or st_dev[0] == rt or not (4 <= st_dev[1] <= 11):
        raise Refuse("timer override sequence not recognised")

    # the rep[] programming before input_register_device: [mov d][str][mov p][str]
    pair = find_rep_pair()
    if not pair or pair[0] > i_data:
        raise Refuse("rep[] stores not found before the timer override")
    i_d, i_p = pair
    rd = is_str(words[i_d], OFF_REP_DELAY)
    rp = is_str(words[i_p], OFF_REP_PERIOD)
    md, mp = imm_before(i_d, rd[0]), imm_before(i_p, rp[0])
    if not md or not mp or (md[1], mp[1]) != (ORIG_DELAY, ORIG_PERIOD):
        raise Refuse("rep[] immediates are not %d/%d" % (ORIG_DELAY, ORIG_PERIOD))
    if not (md[0] < i_d < mp[0] < i_p) or i_p - md[0] != 3:
        raise Refuse("rep[] sequence is not 4 consecutive words")
    first = md[0]
    if not (first <= i_p and i_p < i_data):
        raise Refuse("rep[] stores are not before the timer override")

    edits = []
    # before registration: state->dev store takes the first slot, the rest become NOPs (rep[] = 0)
    for k, new in zip(range(first, first + 4), (words[i_dev], NOP, NOP, NOP)):
        edits.append((foff(k), words[k], new))
    # after registration: rep[REP_DELAY] = delay, rep[REP_PERIOD] = period
    new_seq = (movw(rt, delay), STR_BASE | (rn << 16) | (rt << 12) | OFF_REP_DELAY,
               movw(rt, period), STR_BASE | (rn << 16) | (rt << 12) | OFF_REP_PERIOD)
    for k, new in zip(range(j, j + 4), new_seq):
        edits.append((foff(k), words[k], new))
    return edits, False


def plan_keyup(d, keyup):
    """Edit for the key-up timeout (150 ms in the original) set in input_p_callback."""
    text_off, _fs, _fz, relocs = parse_elf(d)
    # find input_p_callback by its symbol
    shoff = u32(d, 32)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 46)
    raw = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    stro = raw[shstrndx][4]
    secs = {}
    for i, r in enumerate(raw):
        o = stro + r[0]
        secs[d[o:d.index(b"\0", o)].decode()] = (i, r)
    text_idx = secs[".text"][0]
    sym, strtab = secs[".symtab"][1], secs[".strtab"][1]
    fstart = fsize = None
    for o in range(sym[4], sym[4] + sym[5], 16):
        st_name, st_value, st_size, st_info, _other, st_shndx = struct.unpack_from("<IIIBBH", d, o)
        o2 = strtab[4] + st_name
        if st_shndx == text_idx and (st_info & 0xf) == 2 and d[o2:d.index(b"\0", o2)] == b"input_p_callback":
            fstart, fsize = st_value, st_size
    if fstart is None:
        raise Refuse("input_p_callback not found")
    hits = []
    for k in range(fsize // 4):
        w = u32(d, text_off + fstart + 4 * k)
        if mov_imm_value(w, 0) is None:
            continue
        for m in range(k + 1, k + 5):
            v = u32(d, text_off + fstart + 4 * m)
            if (v & 0xff7f0000) == 0xe51f0000 and (v & 0x00800000):
                lit = fstart + 4 * m + 8 + (v & 0xfff)
                if relocs.get(lit) == "msecs_to_jiffies":
                    hits.append((k, mov_imm_value(w, 0), w))
                    break
    hits = [h for h in hits if h[1] in (150, keyup)]
    if len(hits) != 1:
        raise Refuse("key-up timeout site not found (%d candidates)" % len(hits))
    k, val, w = hits[0]
    if val == keyup:
        return [], True
    if val != 150:
        raise Refuse("unexpected key-up timeout %d" % val)
    return [(text_off + fstart + 4 * k, w, movw(0, keyup))], False


def func_range(d, name):
    """(text_file_offset, func_start, func_size) of a global/local FUNC symbol in .text."""
    text_off, _fs, _fz, _relocs = parse_elf(d)
    shoff = u32(d, 32)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 46)
    raw = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    stro = raw[shstrndx][4]
    secs = {}
    for i, r in enumerate(raw):
        o = stro + r[0]
        secs[d[o:d.index(b"\0", o)].decode()] = (i, r)
    text_idx = secs[".text"][0]
    sym, strtab = secs[".symtab"][1], secs[".strtab"][1]
    for o in range(sym[4], sym[4] + sym[5], 16):
        st_name, st_value, st_size, st_info, _other, st_shndx = struct.unpack_from("<IIIBBH", d, o)
        o2 = strtab[4] + st_name
        if st_shndx == text_idx and (st_info & 0xf) == 2 and d[o2:d.index(b"\0", o2)] == name.encode():
            return text_off, st_value, st_size
    raise Refuse("%s not found" % name)


def branch(cond, src, dst):
    """ARM b/bcond at address src to dst."""
    off = (dst - (src + 8)) >> 2
    return cond | (off & 0xffffff)


def plan_fresh(d):
    """A new IR press (frame with repeat == 0) of the key that is already down is handled as a new
    press (release + press, restarting the kernel repeat delay) instead of being merged into the
    previous press by the key-up timer.  Frames with repeat == 1 still just keep the key down.

    input_p_callback, same key as the last one:   beq <same_key>
        same_key:  ldrb r2, [sb, #0x3a]     ; driver repeat flag (never set once the kernel timer is used)
                   cmp  r2, #0
                   beq  rearm_keyup
    becomes
        same_key:  ldrb r2, [sp, #<repeat>] ; repeat byte of the frame being handled
                   cmp  r2, #0
                   beq  new_key             ; fresh press: take the different-key path
                   b    rearm_keyup
    """
    text_off, fstart, fsize = func_range(d, "input_p_callback")
    base = text_off + fstart
    words = [u32(d, base + 4 * i) for i in range(fsize // 4)]
    # repeat byte: first 'ldrb rt, [sp, #imm]' in the function
    rep_off = None
    for w in words:
        if (w & 0xffff0000) == 0xe5dd0000:
            rep_off = w & 0xfff
            break
    if rep_off is None:
        raise Refuse("repeat byte load not found")
    # original site: ldrb rt,[rn,#0x3a] / cmp rt,#0 / beq
    orig = [i for i, w in enumerate(words)
            if (w & 0xfff00fff) == 0xe5d0003a and ((w >> 16) & 0xf) != 13]
    done = [i for i in range(len(words) - 3)
            if (words[i] & 0xffff0fff) == (0xe5dd0000 | rep_off)
            and (words[i + 2] & 0xff000000) == 0x0a000000 and (words[i + 3] & 0xff000000) == 0xea000000]
    if done and not orig:
        return [], True
    if len(orig) != 1:
        raise Refuse("same-key site not found (%d candidates)" % len(orig))
    i = orig[0]
    rt = (words[i] >> 12) & 0xf
    if words[i + 1] != (0xe3500000 | (rt << 16)) or (words[i + 2] & 0xff000000) != 0x0a000000:
        raise Refuse("same-key site has unexpected code")

    def tgt(k):
        off = words[k] & 0xffffff
        off = off - (1 << 24) if off & 0x800000 else off
        return k + 2 + off

    # the caller branch: 'beq same_key' directly after a cmp, whose fall-through is the new-key path
    callers = [k for k, w in enumerate(words) if (w & 0xff000000) == 0x0a000000 and k != i + 2 and tgt(k) == i]
    if len(callers) != 1 or (words[callers[0] - 1] & 0xfff00000) != 0xe1500000:
        raise Refuse("same-key branch not found (%d candidates)" % len(callers))
    new_key = callers[0] + 1
    rearm = tgt(i + 2)
    new = [0xe5dd0000 | (rt << 12) | rep_off,
           words[i + 1],
           branch(0x0a000000, base + 4 * (i + 2), base + 4 * new_key),
           branch(0xea000000, base + 4 * (i + 3), base + 4 * rearm)]
    return [(base + 4 * (i + k), words[i + k], new[k]) for k in range(4)], False


def main(argv):
    check = False
    fresh = True
    delay, period = 600, 100
    keyup = None
    args = list(argv)
    path = None
    while args:
        a = args.pop(0)
        if a == "--check":
            check = True
        elif a == "--delay":
            delay = int(args.pop(0))
        elif a == "--period":
            period = int(args.pop(0))
        elif a == "--no-fresh-press":
            fresh = False
        elif a == "--keyup":
            keyup = int(args.pop(0))
        elif path is None:
            path = a
        else:
            print(__doc__)
            return 1
    if path is None or not (0 < period < 4096 and 0 < delay < 4096):
        print(__doc__)
        return 1
    d = bytearray(open(path, "rb").read())
    try:
        edits, done = plan(bytes(d), delay, period)
    except Refuse as e:
        print("REFUSED: %s" % e)
        return 2
    if fresh:
        try:
            e3, done3 = plan_fresh(bytes(d))
        except Refuse as e:
            print("REFUSED: %s" % e)
            return 2
        edits += e3
        done = done and done3
    if keyup is not None:
        try:
            e2, done2 = plan_keyup(bytes(d), keyup)
        except Refuse as e:
            print("REFUSED: %s" % e)
            return 2
        edits += e2
        done = done and done2
    if done:
        print("already patched, nothing to do")
        return 0
    for off, old, new in edits:
        print("  0x%06x: %08x -> %08x" % (off, old, new))
    if check:
        print("check only, %d word(s) would change" % len(edits))
        return 0
    for off, old, new in edits:
        struct.pack_into("<I", d, off, new)
    # self-check: re-plan must now report "done"
    try:
        _, done = plan(bytes(d), delay, period)
    except Refuse as e:
        print("REFUSED after patching: %s" % e)
        return 2
    if not done:
        print("REFUSED: patched image does not verify")
        return 2
    if fresh and not plan_fresh(bytes(d))[1]:
        print("REFUSED: fresh-press patch does not verify")
        return 2
    if keyup is not None and not plan_keyup(bytes(d), keyup)[1]:
        print("REFUSED: key-up patch does not verify")
        return 2
    open(path, "wb").write(d)
    print("patched %s: kernel autorepeat restored, delay %d ms, period %d ms%s"
          % (path, delay, period, "" if keyup is None else ", key-up timeout %d ms" % keyup))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
